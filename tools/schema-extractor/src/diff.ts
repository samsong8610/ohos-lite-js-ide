import type { ComponentsSchemaFile, FieldSchema } from '@ohjs/schemas';

type Kind = 'attributes' | 'styles' | 'events' | 'methods';
const KINDS: Kind[] = ['attributes', 'styles', 'events', 'methods'];

export interface FieldDiff {
  added: string[];
  removed: string[];
  /** name: old availability → new availability */
  changed: string[];
  /** fields whose documentation text was added, removed or rewritten */
  docChanged?: string[];
}

export interface SchemaDiff {
  from: string;
  to: string;
  componentsAdded: string[];
  componentsRemoved: string[];
  componentAvailability: string[];
  fields: Record<string, Partial<Record<Kind, FieldDiff>>>;
  common: Partial<Record<'attributes' | 'styles' | 'events' | 'directives', FieldDiff>>;
  features: string[];
  imageExtensions: FieldDiff;
}

function diffNames(a: string[], b: string[]): { added: string[]; removed: string[] } {
  const sa = new Set(a);
  const sb = new Set(b);
  return { added: b.filter((x) => !sa.has(x)).sort(), removed: a.filter((x) => !sb.has(x)).sort() };
}

function diffFields(a: Record<string, FieldSchema>, b: Record<string, FieldSchema>): FieldDiff {
  const { added, removed } = diffNames(Object.keys(a), Object.keys(b));
  const changed = Object.keys(a)
    .filter((k) => b[k] && a[k]!.availability !== b[k]!.availability)
    .sort()
    .map((k) => `${k}: ${a[k]!.availability} → ${b[k]!.availability}`);
  const docChanged = Object.keys(a)
    .filter((k) => b[k] && (a[k]!.doc ?? '') !== (b[k]!.doc ?? ''))
    .sort()
    .map(
      (k) =>
        `${k} (${a[k]!.doc === undefined ? 'newly documented' : b[k]!.doc === undefined ? 'doc removed' : 'doc text changed'})`,
    );
  return { added, removed, changed, ...(docChanged.length ? { docChanged } : {}) };
}

const empty = (d: FieldDiff): boolean =>
  !d.added.length && !d.removed.length && !d.changed.length && !d.docChanged?.length;

export function diffSchemas(a: ComponentsSchemaFile, b: ComponentsSchemaFile): SchemaDiff {
  const tags = diffNames(Object.keys(a.components), Object.keys(b.components));
  const fields: SchemaDiff['fields'] = {};
  const componentAvailability: string[] = [];
  for (const tag of Object.keys(a.components).sort()) {
    const ca = a.components[tag]!;
    const cb = b.components[tag];
    if (!cb) continue;
    if (ca.availability !== cb.availability)
      componentAvailability.push(`${tag}: ${ca.availability} → ${cb.availability}`);
    for (const k of KINDS) {
      const d = diffFields(ca[k], cb[k]);
      if (!empty(d)) (fields[tag] ??= {})[k] = d;
    }
  }
  const common: SchemaDiff['common'] = {};
  for (const k of ['attributes', 'styles', 'events', 'directives'] as const) {
    const d = diffFields(a.common[k], b.common[k]);
    if (!empty(d)) common[k] = d;
  }
  const features: string[] = [];
  for (const n of [...new Set([...Object.keys(a.features), ...Object.keys(b.features)])].sort()) {
    const va = a.features[n]?.value;
    const vb = b.features[n]?.value;
    if (va !== vb) features.push(`${n}: ${String(va ?? 'undefined')} → ${String(vb ?? 'undefined')}`);
  }
  return {
    from: a.ohVersion,
    to: b.ohVersion,
    componentsAdded: tags.added,
    componentsRemoved: tags.removed,
    componentAvailability,
    fields,
    common,
    features,
    imageExtensions: { ...diffNames(a.aceLoader.imageExtensions, b.aceLoader.imageExtensions), changed: [] },
  };
}

const list = (xs: string[]): string => (xs.length ? xs.map((x) => `\`${x}\``).join(', ') : '—');

function fieldLines(label: string, d: FieldDiff): string[] {
  const out: string[] = [];
  if (d.added.length) out.push(`- ${label} added: ${list(d.added)}`);
  if (d.removed.length) out.push(`- ${label} removed: ${list(d.removed)}`);
  for (const c of d.changed) out.push(`- ${label} availability: ${c}`);
  if (d.docChanged?.length) out.push(`- ${label} documentation: ${list(d.docChanged)}`);
  return out;
}

export function renderDiffMarkdown(d: SchemaDiff, a: ComponentsSchemaFile, b: ComponentsSchemaFile): string {
  const src = (f: ComponentsSchemaFile): string =>
    f.sources
      .map(
        (s) =>
          `${s.repo}=${s.commit ? s.commit.slice(0, 12) : 'unknown'}${s.tags.length ? ` (${s.tags.join(', ')})` : ''}`,
      )
      .join('; ');
  const lines = [
    `# ArkUI.Lite component schema diff: ${d.from} → ${d.to}`,
    '',
    '<!-- generated by @ohjs/schema-extractor; do not edit -->',
    '',
    `- from: OpenHarmony ${a.ohVersion}${a.provisional ? ' (provisional)' : ''}, target \`${a.target}\`; sources: ${src(a)}`,
    `- to: OpenHarmony ${b.ohVersion}${b.provisional ? ' (provisional)' : ''}, target \`${b.target}\`; sources: ${src(b)}`,
  ];
  if (b.provisional && b.provisionalReason)
    lines.push(`- ⚠ ${b.ohVersion} is provisional: ${b.provisionalReason}`);
  lines.push('', '## Components', '');
  const compLines = [
    ...(d.componentsAdded.length ? [`- added: ${list(d.componentsAdded)}`] : []),
    ...(d.componentsRemoved.length ? [`- removed: ${list(d.componentsRemoved)}`] : []),
    ...d.componentAvailability.map((c) => `- availability: ${c}`),
  ];
  lines.push(...(compLines.length ? compLines : ['No component added, removed or changed availability.']));
  lines.push('', '## Component fields', '');
  const tags = Object.keys(d.fields);
  if (!tags.length) lines.push('No attribute / style / event / method differences.', '');
  for (const tag of tags) {
    lines.push(`### <${tag}>`, '');
    for (const k of KINDS) {
      const fd = d.fields[tag]![k];
      if (fd) lines.push(...fieldLines(k, fd));
    }
    lines.push('');
  }
  lines.push('## Common attributes / styles / events / directives', '');
  const cl = (Object.keys(d.common) as Array<keyof SchemaDiff['common']>).flatMap((k) =>
    fieldLines(k, d.common[k]!),
  );
  lines.push(...(cl.length ? cl : ['No differences.']));
  lines.push('', `## Feature macros (\`targets/${b.target}/acelite_config.h\`)`, '');
  lines.push(...(d.features.length ? d.features.map((f) => `- ${f}`) : ['No differences.']));
  lines.push('', '## ace-loader', '');
  const il = fieldLines('image extensions', d.imageExtensions);
  lines.push(...(il.length ? il : ['No differences in accepted image extensions.']));
  lines.push('');
  return lines.join('\n');
}

// Pure generators for the files the extension writes under `.ohjs/` so VS Code's built-in JS/TS service
// understands a Lite project (ARCHITECTURE §7.1 "JS 语言支持"): an ES5 jsconfig, ambient `@system.*`
// declarations for the selected SDK, and the runtime globals / ViewModel shape. No vscode / fs imports.
import type { SystemModulesFile } from '@ohjs/schemas';
import { parse, printParseErrorCode, type ParseError } from 'jsonc-parser';

export const OHJS_DIR = '.ohjs';
export const JSCONFIG_BASE = 'jsconfig.base.json';
export const TYPES_DIR = 'types';
export const MODULES_DTS = 'system-modules.d.ts';
export const ENV_DTS = 'ohjs-env.d.ts';
/** include entry the root jsconfig.json needs (relative to the workspace root) */
export const TYPES_INCLUDE = `${OHJS_DIR}/${TYPES_DIR}/**/*.d.ts`;
export const BASE_EXTENDS = `./${OHJS_DIR}/${JSCONFIG_BASE}`;

const HEADER = (what: string): string =>
  `// Generated by the OpenHarmony Lite JS extension (${what}). Do not edit: regenerated on SDK change.\n`;

interface ApiTable {
  /** declaration body inside the module, `export default` is added */
  body: string;
  /** whether the shape was read from the C++ sources in the vendored repos */
  verified: boolean;
}

/**
 * Function tables confirmed in ace_engine_lite (5.0.3 / 6.1): router_module.cpp, app_module.cpp,
 * prompt_module.cpp, dfx_module.cpp. The rest are registered by subsystems outside the vendored repos,
 * so they are typed loosely (`any`).
 */
const API: Record<string, ApiTable> = {
  router: {
    verified: true,
    body: `interface RouterOptions { /** page path, e.g. 'pages/detail/detail' */ uri: string; params?: Record<string, any>; }
  const router: {
    /** Replaces the current page (the lite runtime keeps a single page). */
    replace(options: RouterOptions): void;
  };`,
  },
  app: {
    verified: true,
    body: `const app: {
    getInfo(): { appName?: string; versionName?: string; versionCode?: number; [k: string]: any } | undefined;
    terminate(): void;
  };`,
  },
  prompt: {
    verified: true,
    body: `interface DialogButton { text: string; color?: string; }
  interface ShowDialogOptions {
    title?: string;
    message?: string;
    buttons?: DialogButton[];
    success?: (data: { index: number }) => void;
    cancel?: () => void;
    complete?: () => void;
  }
  const prompt: { showDialog(options: ShowDialogOptions): void; };`,
  },
  dfx: {
    verified: true,
    body: `const dfx: {
    screenshotToFile(...args: any[]): any;
    injectEvent(...args: any[]): any;
    dumpDomNode(...args: any[]): any;
    dumpDomTree(...args: any[]): any;
  };`,
  },
};

/** `declare module '@system.x'` / `'@ohos.x'` for every module built into the SDK's target firmware. */
export function generateSystemModulesDts(pack: SystemModulesFile): string {
  const out = [
    HEADER(`@system modules, OpenHarmony ${pack.ohVersion}, target ${pack.target}`),
    '// Only modules registered in OHOS_MODULES (ohos_module_config.h) and enabled for this target are declared,',
    '// so importing anything else is a "Cannot find module" error here and js/unknown-system-module in OHJS.',
    '',
  ];
  for (const m of pack.modules) {
    if (m.availability !== 'available') continue;
    const api = API[m.name];
    const id = m.name.replace(/\W/g, '_');
    for (const cat of pack.categories) {
      out.push(`declare module '@${cat}.${m.name}' {`);
      if (api) out.push(`  ${api.body.replace(/const \w+:/, `const ${id}:`)}`);
      else {
        out.push(
          '  // API surface implemented outside ace_engine_lite; not verified from source, typed loosely.',
        );
        out.push(`  const ${id}: any;`);
      }
      out.push(`  export default ${id};`, '}', '');
    }
  }
  return out.join('\n');
}


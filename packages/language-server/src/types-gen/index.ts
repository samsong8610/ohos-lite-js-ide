/** `.ohjs/jsconfig.base.json` (paths relative to `.ohjs/`, as TypeScript resolves them from the base file). */
export function jsconfigBase(): string {
  const cfg = {
    compilerOptions: {
      target: 'ES5',
      lib: ['es5'],
      allowJs: true,
      checkJs: false,
      module: 'ES2015',
      moduleResolution: 'node',
      noEmit: true,
    },
    include: ['../**/src/main/js/**/*.js', `${TYPES_DIR}/**/*.d.ts`],
    exclude: ['../**/node_modules', '../**/build'],
  };
  return `${JSON.stringify(cfg, null, 2)}\n`;
}

export type JsconfigPlan =
  | { action: 'create'; content: string }
  | { action: 'none' }
  | { action: 'merge'; content: string; changes: string[] }
  | { action: 'unparsable'; error: string };

/**
 * Decides what to do with the user's root jsconfig.json. Never touches a file that already extends the
 * base; otherwise proposes a merge (adds `extends`, keeps any existing base as an array — TS ≥ 5.0 —
 * and appends the generated types to an explicit `include`). The caller asks before writing a merge.
 * Comments in an existing file are not preserved by a merge (JSON.stringify), which the prompt says.
 */
export function planJsconfig(existing: string | undefined): JsconfigPlan {
  if (existing === undefined)
    return { action: 'create', content: `${JSON.stringify({ extends: BASE_EXTENDS }, null, 2)}\n` };

  const errors: ParseError[] = [];
  const parsed: unknown = parse(existing, errors, { allowTrailingComma: true });
  if (errors.length > 0)
    return {
      action: 'unparsable',
      error: `${printParseErrorCode(errors[0]!.error)} at offset ${errors[0]!.offset}`,
    };
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed))
    return { action: 'unparsable', error: 'not a JSON object' };
  const cfg = parsed as Record<string, unknown>;
  const norm = (s: unknown): string => String(s).replace(/\\/g, '/').replace(/^\.\//, '');
  const target = norm(BASE_EXTENDS);
  const ext = cfg.extends;
  const exts = ext === undefined ? [] : Array.isArray(ext) ? ext : [ext];
  const changes: string[] = [];
  if (!exts.some((e) => norm(e) === target)) {
    cfg.extends = exts.length === 0 ? BASE_EXTENDS : [...exts, BASE_EXTENDS];
    changes.push(`extends += ${BASE_EXTENDS}`);
  }
  // an explicit include replaces the base's include, so the generated declarations must be listed too
  if (Array.isArray(cfg.include) && !cfg.include.some((i) => norm(i) === TYPES_INCLUDE)) {
    cfg.include = [...cfg.include, TYPES_INCLUDE];
    changes.push(`include += ${TYPES_INCLUDE}`);
  }
  if (changes.length === 0) return { action: 'none' };
  return { action: 'merge', content: `${JSON.stringify(cfg, null, 2)}\n`, changes };
}
